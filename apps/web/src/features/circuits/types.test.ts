import captured from "./fixtures/captured.json";
import { EXAMPLES } from "./examples";
import {
  MalformedAnswerError,
  readCircuitDocument,
  readConventions,
  readPaperCircuits,
  readPaperExport,
  readQasmExport,
  readReading,
  readResult,
} from "./types";

interface Recorded {
  name: string;
  path: string;
  request: Record<string, unknown> | null;
  status: number;
  response: unknown;
}
const recorded = captured as Recorded[];
const ok = (path: string) =>
  recorded.filter((entry) => entry.path === path && entry.status === 200);
const okUnder = (pattern: RegExp) =>
  recorded.filter((entry) => pattern.test(entry.path) && entry.status === 200);
const answer = (name: string) => {
  const entry = recorded.find((item) => item.name === name);
  if (!entry) throw new Error(`no recorded answer ${name}`);
  return entry.response;
};

describe("the recorded answers of the API", () => {
  it.each(ok("/circuits/parse").map((entry) => [entry.name, entry.response]))(
    "read as a gate list: %s",
    (_, body) => {
      const reading = readReading(body);
      expect(reading.circuits).toHaveLength(reading.raw.length);
      for (const circuit of reading.circuits) expect(circuit.format).toBe("circuit/1");
    },
  );

  it.each(
    ok("/circuits/run")
      .concat(ok("/circuits/check"))
      .map((entry) => [entry.name, entry.response]),
  )("read as a simulator result: %s", (_, body) => {
    const result = readResult(body);
    expect(["ok", "symbolic", "refused"]).toContain(result.status);
    expect(Object.keys(result.conventions).length).toBeGreaterThan(5);
    if (result.status === "refused") {
      expect(result.refused.length).toBeGreaterThan(0);
      expect(result.circuits).toEqual([]);
    }
  });

  it("read the conventions with the gate table", () => {
    const entry = recorded.find((item) => item.path === "/circuits/conventions");
    const conventions = readConventions(entry?.response);
    expect(conventions.gates.length).toBeGreaterThan(15);
    expect(conventions.gates.find((gate) => gate.name === "rzz")).toMatchObject({
      targets: 2,
      params: 1,
    });
    expect(conventions.limits.statevector_wires).toBe(20);
  });

  it("keep the amplitudes, the probabilities and the unitary of a simulation", () => {
    const entry = recorded.find((item) => item.name === "run bell unitary");
    const [part] = readResult(entry?.response).circuits;
    expect(part?.state).toHaveLength(4);
    expect(part?.probabilities).toEqual({ wires: [1, 2], values: [0.5, 0, 0, 0.5] });
    expect(part?.unitary).toHaveLength(4);
  });

  it("keep a symbolic result's unbound names, and a check's comparison", () => {
    const symbolic = readResult(recorded.find((item) => item.name === "run symbolic")?.response);
    expect(symbolic).toMatchObject({
      status: "symbolic",
      unbound: ["theta"],
      parameters: ["theta"],
    });
    expect(symbolic.circuits[0]?.state).toBeNull();
    const check = readResult(
      recorded.find((item) => item.name === "check bell state not equal")?.response,
    );
    expect(check.equalToTarget).toBe(false);
    expect(check.comparisons[0]).toMatchObject({ equal: false, method: "arrays" });
  });
});

describe("the recorded answers of the OpenQASM export", () => {
  const TELEPORTATION = "c7f460355b1958c3e6cf45b6d3234766cd8c9d49a5a9265864030a0606907a44";

  it("cover every export endpoint, so a test of the screen is a test of the API", () => {
    expect(ok("/circuits/qasm").length).toBeGreaterThan(5);
    expect(okUnder(/^\/documents\/[0-9a-f]+\/circuits$/).length).toBeGreaterThan(1);
    expect(okUnder(/^\/documents\/[0-9a-f]+\/qasm$/).length).toBeGreaterThan(1);
  });

  it.each(ok("/circuits/qasm").map((entry) => [entry.name, entry.response]))(
    "read as a circuit export: %s",
    (_, body) => {
      const exported = readQasmExport(body);
      if (exported.status === "refused") {
        expect(exported.programs).toEqual([]);
        expect(exported.reasons.length).toBeGreaterThan(0);
      } else {
        expect(exported.programs.length).toBeGreaterThan(0);
        for (const program of exported.programs) {
          expect(program.filename).toBe(`circuit-p0${program.part}.qasm`);
          expect(program.text).toMatch(/^\/\/ Generated by research-api .*\nOPENQASM 3\.0;\n/s);
          expect(program.text.endsWith("\n")).toBe(true);
        }
      }
    },
  );

  it.each(
    okUnder(/\/circuits$/)
      .filter((entry) => entry.path.startsWith("/documents/"))
      .map((entry) => [entry.name, entry.response]),
  )("read as a paper's circuit blocks: %s", (_, body) => {
    const paper = readPaperCircuits(body);
    expect(paper.docId).toMatch(/^[0-9a-f]{64}$/);
    paper.blocks.forEach((block, index) => {
      expect(block.block).toBe(index + 1);
      expect(block.raw).toHaveLength(block.circuits.length);
    });
  });

  it.each(okUnder(/^\/documents\/[0-9a-f]+\/qasm$/).map((entry) => [entry.name, entry.response]))(
    "read as a paper's export: %s",
    (_, body) => {
      const paper = readPaperExport(body);
      for (const circuit of paper.circuits) {
        for (const program of circuit.programs) {
          expect(program.filename).toBe(
            `${paper.docId.slice(0, 16)}-b0${circuit.block}-c0${circuit.circuit}-p0${program.part}.qasm`,
          );
          expect(program.text).toContain("// Generated by docingest");
        }
      }
    },
  );

  it("keep each program's text, file name and counts", () => {
    const [program] = readQasmExport(answer("qasm bell")).programs;
    expect(program).toMatchObject({ filename: "circuit-p01.qasm", part: 1, sign: null });
    expect(program?.text).toContain("qubit[2] q;\n\nh q[0];\ncx q[0], q[1];\n");
    expect(program).toMatchObject({ nQubits: 2, nClbits: 0 });
    const measured = readQasmExport(answer("qasm measured")).programs[0];
    expect(measured?.nClbits).toBe(2);
    expect(measured?.text).toContain("bit[2] c;");
  });

  it("give one program per side of a drawn equality, with the sign", () => {
    const { programs } = readQasmExport(answer("qasm hzh equals x"));
    expect(programs.map((p) => [p.filename, p.part, p.sign])).toEqual([
      ["circuit-p01.qasm", 1, null],
      ["circuit-p02.qasm", 2, "="],
    ]);
  });

  it("name a missing value as a key, and the reader's name of the symbol", () => {
    expect(readQasmExport(answer("qasm symbolic"))).toMatchObject({
      status: "refused",
      symbols: ["theta"],
      unbound: ["theta"],
    });
    expect(readQasmExport(answer("qasm two-character subscript"))).toMatchObject({
      status: "refused",
      symbols: ["theta_12"],
      unbound: ["theta_{12}"],
    });
    expect(readQasmExport(answer("qasm two-character subscript bound")).status).toBe("ok");
  });

  it("write a bound value as typed, pi standing for \\pi", () => {
    const [program] = readQasmExport(answer("qasm symbolic bound")).programs;
    expect(program?.text).toContain("// bound: theta = pi/4\n");
    expect(program?.text).toContain("ry(pi/4.0) q[0];");
  });

  it("list a key no symbol uses, and a refusal's reasons word for word", () => {
    expect(readQasmExport(answer("qasm stray key")).unmatched).toEqual(["theta"]);
    expect(readQasmExport(answer("qasm partial refused")).reasons).toEqual([
      "status: the circuit was read as 'partial', not 'parsed'",
    ]);
  });

  it("list the teleportation paper's two blocks and export the second one", () => {
    const paper = readPaperCircuits(answer("paper circuits teleportation"));
    expect(paper.docId).toBe(TELEPORTATION);
    expect(paper.sourceName).toBe("synthetic-teleportation-circuit.tex");
    expect(paper.blocks.map((block) => [block.block, block.status, block.circuits.length])).toEqual(
      [
        [1, "partial", 1],
        [2, "parsed", 1],
      ],
    );
    expect(paper.blocks[1]?.latex).toContain("\\begin{quantikz}");
    const exported = readPaperExport(answer("paper qasm teleportation"));
    expect(exported.circuits.map((c) => [c.block, c.circuit, c.status])).toEqual([
      [1, 1, "refused"],
      [2, 1, "ok"],
    ]);
    expect(exported.circuits[0]?.reasons).toEqual([
      "status: the circuit was read as 'partial', not 'parsed'",
    ]);
    expect(exported.circuits[1]?.programs.map((p) => p.filename)).toEqual([
      "c7f460355b1958c3-b02-c01-p01.qasm",
    ]);
    expect(exported.warnings).toEqual([]);
  });

  it("say when a paper has no circuits, and when a key matches no symbol", () => {
    expect(readPaperCircuits(answer("paper circuits none")).blocks).toEqual([]);
    const none = readPaperExport(answer("paper qasm none"));
    expect(none.circuits).toEqual([]);
    expect(none.warnings).toEqual(["synthetic-transmon-coherence.pdf: no circuits found"]);
    expect(readPaperExport(answer("paper qasm stray key")).warnings).toEqual([
      "binding 'theta' matches no symbol of any exported circuit",
    ]);
  });

  it("are problems with a pointer for a bad key and for an unknown paper", () => {
    const entries = [
      "qasm bad key",
      "paper qasm bad key",
      "paper circuits unknown",
      "paper qasm unknown",
    ].map((name) => recorded.find((item) => item.name === name));
    expect(entries.map((entry) => entry?.status)).toEqual([422, 422, 404, 404]);
    expect((entries[0]?.response as { errors: { path: string }[] }).errors[0]?.path).toBe(
      "/values/thetta",
    );
    expect((entries[1]?.response as { errors: { path: string }[] }).errors[0]?.path).toBe(
      "/values/pi",
    );
  });
});

describe("the examples of the screen", () => {
  it("are the circuits that were recorded, so a test of the screen is a test of the examples", () => {
    const requests = new Map(
      recorded
        .filter((entry) => entry.path === "/circuits/parse")
        .map((entry) => [entry.name, (entry.request as { latex: string }).latex]),
    );
    const names: Record<string, string> = {
      bell: "parse bell",
      ghz: "parse ghz qcircuit",
      rotation: "parse rotation",
      hzhEqualsX: "parse hzh equals x",
      cnotFromCz: "parse cnot from cz",
      qft3: "parse qft3",
      measured: "parse measured",
      partial: "parse partial",
      bundle: "parse bundle",
    };
    for (const example of EXAMPLES.filter((item) => item.kind === "latex")) {
      expect(example.text, example.id).toBe(requests.get(names[example.id] ?? ""));
    }
  });

  it("includes a circuit/1 example that is the recorded one", () => {
    const json = EXAMPLES.find((example) => example.id === "bellJson");
    const entry = recorded.find((item) => item.name === "run bad input");
    expect(json?.text).toBe((entry?.request as { circuit_json: string }).circuit_json);
  });
});

describe("answers that are not what the contract says", () => {
  it("refuses a gate list with a missing or wrong field", () => {
    for (const bad of [
      null,
      "x",
      { status: "weird", text: "", circuits: [] },
      { status: "parsed", circuits: [] },
      { status: "parsed", text: "", circuits: "no" },
      { status: "parsed", text: "", circuits: [{ wires: 1 }] },
      { status: "parsed", text: "", circuits: [{ wires: 1, parts: [[["x"]]] }] },
      {
        status: "parsed",
        text: "",
        circuits: [{ wires: 1, parts: [[[{ kind: "gate", targets: ["a"] }]]] }],
      },
    ]) {
      expect(() => readReading(bad), JSON.stringify(bad)).toThrow(MalformedAnswerError);
    }
  });

  it("refuses a result with a missing or wrong field", () => {
    const base = { format: "quantum-sim-result/1", command: "run", status: "ok" };
    for (const bad of [
      null,
      { ...base, format: "other" },
      { ...base, command: "walk" },
      { ...base, status: "maybe" },
      { ...base, conventions: { a: 1 } },
      { ...base, refused: [1] },
      { ...base, values: { theta: "x" } },
      { ...base, circuits: "no" },
      { ...base, circuits: [{ part: 1 }] },
      { ...base, circuits: [{ part: 1, wires: 1, state: [1] }] },
      { ...base, circuits: [{ part: 1, wires: 1, unitary: [[1]] }] },
      { ...base, circuits: [{ part: 1, wires: 1, probabilities: { wires: [1], values: "no" } }] },
      { ...base, comparisons: [{ between: ["a"], equal: "yes" }] },
      { ...base, equal_to_target: "yes" },
    ]) {
      expect(() => readResult(bad), JSON.stringify(bad)).toThrow(MalformedAnswerError);
    }
  });

  it("accepts the smallest result", () => {
    const result = readResult({
      format: "quantum-sim-result/1",
      command: "check",
      status: "refused",
      refused: ["why"],
    });
    expect(result).toMatchObject({
      command: "check",
      refused: ["why"],
      circuits: [],
      equalToTarget: null,
    });
  });

  it("refuses an export with a missing or wrong field", () => {
    const program = {
      filename: "circuit-p01.qasm",
      part: 1,
      sign: null,
      text: "OPENQASM 3.0;\n",
      n_qubits: 1,
      n_clbits: 0,
    };
    const base = {
      status: "ok",
      programs: [program],
      reasons: [],
      notes: [],
      symbols: [],
      unmatched: [],
      unbound: [],
    };
    expect(readQasmExport(base).programs[0]?.nQubits).toBe(1);
    for (const bad of [
      null,
      [],
      { ...base, status: "symbolic" },
      { ...base, programs: "no" },
      { ...base, reasons: [1] },
      { ...base, unbound: undefined },
      { ...base, symbols: undefined },
      { ...base, unmatched: [null] },
      { ...base, programs: [{ ...program, filename: "../x.qasm" }] },
      { ...base, programs: [{ ...program, filename: "a/b.qasm" }] },
      { ...base, programs: [{ ...program, filename: "circuit.txt" }] },
      { ...base, programs: [{ ...program, part: 1.5 }] },
      { ...base, programs: [{ ...program, sign: 1 }] },
      { ...base, programs: [{ ...program, text: null }] },
      { ...base, programs: [{ ...program, n_clbits: -1 }] },
    ]) {
      expect(() => readQasmExport(bad), JSON.stringify(bad)).toThrow(MalformedAnswerError);
    }
  });

  it("refuses a paper's blocks or export with a missing or wrong field", () => {
    const paper = { doc_id: "ab", source_name: "x.tex" };
    for (const bad of [
      null,
      { ...paper },
      { ...paper, blocks: "no" },
      { ...paper, blocks: [{ block: 1, latex: "", status: "weird", circuits: [] }] },
      { ...paper, blocks: [{ block: 1, latex: 1, status: "parsed", circuits: [] }] },
      { ...paper, blocks: [{ block: 1, latex: "", status: "parsed", circuits: [{ wires: "1" }] }] },
      { doc_id: 1, source_name: "x.tex", blocks: [] },
    ]) {
      expect(() => readPaperCircuits(bad), JSON.stringify(bad)).toThrow(MalformedAnswerError);
    }
    const circuit = {
      block: 1,
      circuit: 1,
      status: "refused",
      programs: [],
      reasons: ["why"],
      notes: [],
      unbound: [],
    };
    expect(readPaperExport({ ...paper, circuits: [circuit], warnings: [] }).circuits).toHaveLength(
      1,
    );
    for (const bad of [
      null,
      { ...paper, circuits: [], warnings: "no" },
      { ...paper, circuits: "no", warnings: [] },
      { ...paper, circuits: [{ ...circuit, block: "1" }], warnings: [] },
      { ...paper, circuits: [{ ...circuit, status: "maybe" }], warnings: [] },
      { ...paper, circuits: [{ ...circuit, unbound: undefined }], warnings: [] },
    ]) {
      expect(() => readPaperExport(bad), JSON.stringify(bad)).toThrow(MalformedAnswerError);
    }
  });

  it("refuses conventions with a missing or wrong field", () => {
    for (const bad of [
      null,
      {},
      { conventions: { a: "b" }, gates: "no", limits: {} },
      { conventions: { a: "b" }, gates: [{ name: 1 }], limits: {} },
    ]) {
      expect(() => readConventions(bad), JSON.stringify(bad)).toThrow(MalformedAnswerError);
    }
  });

  it("reads a document with no kind, label or legends, and refuses a bad one", () => {
    expect(readCircuitDocument({ wires: 1, parts: [] })).toMatchObject({
      format: "circuit/1",
      wire_labels: [],
    });
    expect(readCircuitDocument({ wires: "1", parts: [] })).toBeNull();
    expect(readCircuitDocument({ wires: 1, parts: [], wire_labels: [1] })).toBeNull();
    expect(readCircuitDocument({ wires: 1, parts: ["x"] })).toBeNull();
  });

  it("says in the error which answer it was", () => {
    expect(() => readReading(null)).toThrow("gate list");
  });
});
